此一原理成立的理由有三。首先且最為根本者為投資機會：今日取得的資金可立即投入運用而產生報酬，因此放棄今日收款即放棄了這段期間的獲利機會。其次為通貨膨脹：物價上漲侵蝕購買力，未來的同一金額所能購買的商品較少。第三為不確定性：未來的收款存在無法實現的風險。三者之中，投資機會之所以最為根本，是因為即使在沒有通膨且完全無風險的世界裡，時間價值依然存在——資金本身具有生產力。

由此發展出兩個核心運算。終值的計算為現值乘以一加利率的期數次方，用以將今日的金額推算至未來；現值的計算則為未來金額除以一加利率的期數次方，用以將未來的金額折算至今日。兩者互為逆運算，前者所乘的複利因子與後者所除的折現因子互為倒數。複利之所以重要，在於它使資產呈指數而非線性成長：在年利率百分之十的條件下，單利經過三十年僅使本金成為四倍，複利則成為約十七點四五倍，差距隨期數增加而急遽擴大。

折現率是整個運算的關鍵參數，其意義可從三個角度理解，而三者實指同一件事。就投資人而言，它是機會成本，代表將資金投入此處所放棄的其他用途報酬；就風險承擔而言，它是必要報酬率，即承擔該項風險所要求的最低回報；就企業而言，它是資金成本，即取得該筆資金所須支付的代價。由此可導出一條貫穿財管全科的原則：風險愈高則折現率愈高，折現率愈高則現值愈低。

