更重要的是口徑一致原則：名目現金流必須以名目折現率折現，實質現金流必須以實質折現率折現。若以名目折現率折現未計入通膨的實質現金流，將系統性低估專案價值；反之則高估。此為資本預算實務中最常見的錯誤之一，且因兩種利率的數值差距通常不大而不易被察覺。

折現率的高低對評價結果的影響極為顯著，且此影響隨期間拉長而放大。以十年後的一百萬元為例，在折現率為百分之五時其現值約為六十一點四萬元，在百分之十時則降至約三十八點六萬元。折現率提高一倍，現值減少近四成。若將期間延長至三十年，同樣的折現率差異所造成的現值落差將更為懸殊。

