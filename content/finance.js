在年金的分類上，尚須區分普通年金與期初年金。普通年金的現金流發生於每期期末，期初年金則發生於每期期初。由於期初年金的每一筆現金流均較普通年金提早一期發生、少折現一期，其價值較高，兩者的換算方式為普通年金的現值乘以一加利率。實務上房貸還款與債券利息多屬期末，房租、保費與租賃則多為期初，判斷的關鍵在於第一筆現金流發生於時點零或時點一。此一區分是財管計算題最高頻的陷阱之一。

